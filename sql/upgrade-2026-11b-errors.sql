-- 2026-11b 업그레이드: 오류 기록 표 (교사 화면 ⚠️ 알림)
-- Supabase SQL Editor에서 한 번 실행. 여러 번 실행해도 안전. 기존 표·행은 건드리지 않음 (새 표 하나만).
-- 이 표가 없어도 앱은 그대로 동작하고 오류 기록만 건너뜀.
begin;
create table if not exists public.error_log (
  id      bigint generated by default as identity primary key,
  at      timestamptz not null default now(),
  source  text not null default 'server' check (source in ('server', 'teacher', 'student')),  -- 서버 / 교사 화면 / 학생 화면
  method  text,
  path    text,            -- 주소 (쿼리 문자열은 저장 안 함)
  status  int,
  message text,            -- 오류 글 (300자까지). 학생 답·토큰은 넣지 않음
  detail  jsonb
);
create index if not exists error_log_at_idx on public.error_log (at desc);
-- 다른 표와 같이 RLS만 켜고 정책 없음 → 공개 키(anon)로는 읽기·쓰기 불가, Worker(서비스 키)만
alter table public.error_log enable row level security;
commit;
-- 확인: select count(*) from public.error_log;   (30일 지난 기록은 교사 화면이 열 때 Worker가 지움)
