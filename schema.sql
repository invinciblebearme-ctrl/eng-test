-- 2학기 영어 확인 문제·단원평가 — Supabase 표 (처음 만들 때 SQL Editor에서 한 번 실행)
-- 브라우저는 Supabase에 직접 접속하지 않고 Cloudflare Worker(서비스 키)를 거칩니다.
-- RLS를 켜고 정책을 만들지 않아 공개 키(anon)로는 아무것도 읽거나 쓸 수 없습니다.

create table if not exists public.students (
  id         bigint generated by default as identity primary key,
  grade      int  not null default 4,                                  -- 학년
  class_no   int  not null check (class_no between 1 and 15),
  number     int  not null check (number > 0),
  name       text not null,
  login_ids  text[] not null default '{}',                             -- 학생 계정 ID (소문자, 여러 개 가능)
  created_at timestamptz not null default now(),
  constraint students_grade_class_no_number_key unique (grade, class_no, number)
);

create table if not exists public.submissions (
  id           bigint generated by default as identity primary key,
  student_id   bigint not null references public.students(id) on delete cascade,
  concept      int    not null check (concept between 1 and 100),     -- 시험(세트) 번호
  attempt      int    not null default 1,                             -- 몇 번째 풀이 (재출제하면 2, 3…)
  answers      jsonb  not null,
  auto         jsonb  not null,                                       -- 자동 채점 [true/false…]
  overrides    jsonb  not null default '{}',                          -- 교사가 고친 O/X
  ai           jsonb,                                                 -- AI 채점 제안 {문항: {ok, reason, why}}
  feedback_draft text,                                                -- 예약 작업이 쓴 피드백 초안 (확정 때 공개)
  status       text   not null default 'submitted' check (status in ('submitted','graded')),
  feedback     text,
  submitted_at timestamptz not null default now(),
  graded_at    timestamptz,
  unique (student_id, concept)
);

-- 재출제 때 이전 풀이를 보관
create table if not exists public.submission_history (
  id           bigint generated by default as identity primary key,
  student_id   bigint not null references public.students(id) on delete cascade,
  concept      int    not null,
  attempt      int    not null,
  answers      jsonb  not null,
  auto         jsonb  not null,
  overrides    jsonb  not null default '{}',
  ai           jsonb,
  feedback_draft text,
  status       text   not null,
  feedback     text,
  submitted_at timestamptz,
  graded_at    timestamptz,
  archived_at  timestamptz not null default now()
);

-- Claude 예약 작업이 남기는 결과 분석 보고서 (교사 화면 📊 분석)
create table if not exists public.ai_reports (
  id         bigint generated by default as identity primary key,
  grade      int  not null,
  title      text not null,
  body       text not null,
  created_at timestamptz not null default now()
);

-- 시험 열기/닫기 (행이 없으면 열림)
create table if not exists public.test_settings (
  concept    int primary key check (concept between 1 and 100),
  enabled    boolean not null default true,
  updated_at timestamptz not null default now()
);

create index if not exists students_login_idx on public.students using gin (login_ids);
create index if not exists submissions_student_idx on public.submissions(student_id);
create index if not exists submission_history_sc_idx on public.submission_history(student_id, concept);

alter table public.students           enable row level security;
alter table public.submissions        enable row level security;
alter table public.submission_history enable row level security;
alter table public.test_settings      enable row level security;
alter table public.ai_reports         enable row level security;
